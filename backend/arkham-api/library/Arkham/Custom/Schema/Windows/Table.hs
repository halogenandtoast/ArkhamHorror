{- | Which window each 'Arkham.Matcher.WindowMatcher' fires on.

Only the card builder reads this. Nothing in the engine consults it, so it
cannot change how a window matches -- it exists so the editor can say what an
ability's @$w0@, @$w1@, … are, which it otherwise has to ask the author.

The engine's own answer lives in 'Arkham.Helpers.Window.windowMatches' as case
arms, which is control flow rather than data and so cannot be reified. This
table is the same knowledge written down. It is checked against the real
constructors of both types at compile time by "Arkham.Custom.Schema.Windows",
which fails the build if an entry names something that does not exist or if a
matcher is missing -- so adding a 'WindowMatcher' forces a decision here rather
than silently leaving the editor guessing.

A matcher that fires on no window of its own gets an explicit empty list: the
combinators ('AnyWindow', 'NotWindow', 'OrWindowMatcher', 'WindowWhen') and the
few matchers that ask about state rather than an event.

Names are the windows' /constructors/, not their pattern synonyms: a matcher
written against @Window.PlacedHorror@ is recorded as @PlacedToken@, which is
what the window serializes as and therefore what @$wN@ indexes into.
-}
